const path = require('node:path');
const evidence = process.env.AUDIT_OUTPUT || path.join(__dirname, '../results');
require('node:fs').mkdirSync(evidence, { recursive: true });
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
(async () => {
    const b = await chromium.launch({ executablePath: process.env.CHROME_PATH || '/opt/google/chrome/chrome', args: ['--no-sandbox'] });
    const p = await b.newPage({ viewport: { width: 390, height: 844 } });
    p.setDefaultTimeout(20000);
    const checks = [], errors = [];
    p.on('pageerror', e => errors.push(e.message));
    const check = (name, ok) => { assert.ok(ok, name); checks.push(name); console.log('PASS', name); };
    const root = process.env.AUDIT_URL || 'http://127.0.0.1:3113';
    await p.goto(root);
    await p.getByRole('link', { name: 'Explorar catálogo', exact: true }).click();
    await p.getByRole('status').filter({ hasText: '20 prendas' }).waitFor();
    await p.getByRole('button', { name: 'Abrir menú' }).click();
    await p.getByRole('navigation', { name: 'Móvil', exact: true }).getByRole('link', { name: 'Ofertas', exact: true }).waitFor({ state: 'visible' });
    await p.keyboard.press('Escape');
    check('Menu Escape closes and restores focus', await p.getByRole('button', { name: 'Abrir menú' }).evaluate(x => x === document.activeElement));
    await p.getByRole('button', { name: /^Filtros/ }).click();
    await p.locator('#panel-m-categoria').selectOption('mujer');
    await p.waitForURL(/categoria=mujer/);
    await p.getByRole('button', { name: 'Quitar Categoría: Mujer' }).waitFor();
    await p.locator('#panel-m-marca').selectOption('zara');
    await p.waitForURL(/marca=zara/);
    await p.getByRole('button', { name: 'Quitar Marca: Zara' }).click();
    await p.waitForURL(url => url.searchParams.get('categoria') === 'mujer' && !url.searchParams.has('marca'));
    check('Removing one chip preserves other filters', true);
    check('Removed chip restores focus to search', await p.getByRole('searchbox').evaluate(x => x === document.activeElement));
    await p.locator('#panel-m-categoria').focus();
    await p.keyboard.press('Escape');
    check('Filter Escape returns focus', await p.getByRole('button', { name: /^Filtros/ }).evaluate(x => x === document.activeElement));
    await p.getByRole('button', { name: 'Limpiar filtros', exact: true }).click();
    await p.waitForURL(root + '/catalogo');
    await p.evaluate(() => history.pushState({}, '', '/catalogo?marca=zara'));
    await p.getByRole('button', { name: 'Quitar Marca: Zara' }).waitFor();
    await p.goBack();
    await p.getByRole('button', { name: 'Quitar Marca: Zara' }).waitFor({ state: 'detached' });
    check('Browser history updates filters', true);
    await p.getByRole('searchbox').fill('zzzzsinresultado');
    await p.getByRole('button', { name: 'Buscar', exact: true }).click();
    await p.getByRole('status').filter({ hasText: 'Sin resultados' }).waitFor();
    check('Search has empty state and reset', await p.getByRole('button', { name: 'Limpiar filtros', exact: true }).count() > 0);
    await p.goto(root + '/producto/chaqueta-cuero-vintage');
    await p.getByRole('button', { name: 'Agregar al carrito', exact: true }).waitFor();
    check('Mobile product heading precedes gallery', await p.locator('h1').evaluate(x => x.getBoundingClientRect().top < document.querySelector('main img').getBoundingClientRect().top));
    await p.getByRole('button', { name: /Ver foto.*detalle del estado/ }).click();
    check('Defect photo labelled', await p.getByRole('status').filter({ hasText: 'Detalle del estado de la prenda' }).isVisible());
    await p.getByRole('button', { name: 'Agregar al carrito', exact: true }).click();
    await p.getByRole('link', { name: 'Carrito, 1 prenda(s)' }).click();
    await p.getByRole('heading', { name: 'Carrito', exact: true }).waitFor();
    await p.getByRole('link', { name: 'Ir al checkout' }).click();
    await p.getByRole('button', { name: 'Continuar al despacho' }).click();
    await p.locator('[aria-invalid=true]').first().waitFor();
    check('Invalid checkout focuses first field', await p.locator('[name=fullName]').evaluate(x => x === document.activeElement));
    for (const [name, value] of Object.entries({ fullName: 'Prueba Auditoría', email: 'audit@example.test', phone: '+56912345678', street: 'Calle de prueba 123', comuna: 'Santiago', region: 'Metropolitana' }))
        await p.locator(`[name=${name}]`).fill(value);
    await p.getByRole('button', { name: 'Continuar al despacho' }).click();
    await p.getByRole('radio').first().waitFor();
    await p.getByRole('radio').first().focus();
    await p.keyboard.press('ArrowDown');
    check('Shipping keyboard radio selection', await p.getByRole('radio').nth(1).isChecked());
    await p.goto(root + '/catalogo');
    await p.getByRole('link', { name: 'Saltar al contenido' }).focus();
    await p.keyboard.press('Enter');
    check('Skip link focuses main', await p.locator('main').evaluate(x => x === document.activeElement));
    await p.emulateMedia({ reducedMotion: 'reduce' });
    await p.goto(root);
    check('Reduced motion respected', await p.locator('h1').evaluate(x => parseFloat(getComputedStyle(x).animationDuration) < 0.01));
    await p.emulateMedia({ reducedMotion: 'no-preference' });
    for (const width of [320, 768, 1440]) {
        await p.setViewportSize({ width, height: 900 });
        for (const path of ['/', '/catalogo', '/producto/chaqueta-cuero-vintage', '/login', '/carrito']) {
            await p.goto(root + path);
            await p.waitForTimeout(500);
            check(`No overflow ${width}px ${path}`, await p.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
        }
    }
    check('No uncaught browser exceptions', errors.length === 0);
    fs.writeFileSync(path.join(evidence, 'flows.json'), JSON.stringify({ checks, errors }, null, 2));
    await b.close();
})().catch(e => { console.error(e); process.exit(1); });
